const browser = (...args) => execFileSync('agent-browser', ['--session', session, ...args], { cwd: root, encoding: 'utf8', timeout: 45_000 }).trim();
const click = name => {
  browser('eval', `[...document.querySelectorAll('button')].find(b=>b.textContent===${JSON.stringify(name)})?.scrollIntoView({block:'center'})`);
  return browser('find', 'role', 'button', 'click', '--name', name);
};
const wait = text => browser('wait', '--text', text);
const evaluate = expression => JSON.parse(browser('eval', expression));
const fill = (label, value) => browser('find', 'label', label, 'fill', String(value));
const screenshot = name => browser('screenshot', `${output}${name}.png`);
const move = (x, y) => browser('mouse', 'move', String(Math.round(x)), String(Math.round(y)));
const check = name => {
  browser('eval', `[...document.querySelectorAll('input[type=checkbox]')].find(e=>e.closest('label').textContent.startsWith(${JSON.stringify(name)}))?.scrollIntoView({block:'center'})`);
  return browser('find', 'label', name, 'check');
};
