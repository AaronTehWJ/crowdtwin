import { useEffect, useState } from 'react';
import { AuditReportSchema, type AuditReport } from '@crowdtwin/contracts';
import { api, money, sourceLabel } from '../api';

type Report = AuditReport & { narrativeSource: string; coordinatorSource: string };
export function RiskDesk({ runId }: { runId: string }) {
  const [report, setReport] = useState<Report>();
  const [error, setError] = useState('');
  const [attempt, setAttempt] = useState(0);
  useEffect(() => {
    setReport(undefined); setError('');
    const controller = new AbortController();
    void api<Report>(`/runs/${runId}/audit`, undefined, controller.signal).then(value => {
      const parsed = AuditReportSchema.parse(value);
      if (parsed.runId !== runId || parsed.scenarios.length !== 3 || new Set(parsed.scenarios.map(s => s.scenarioName)).size !== 3)
        throw new Error('Audit must contain all three actual summaries for the selected run');
      if (!controller.signal.aborted) setReport({ ...parsed, narrativeSource: value.narrativeSource, coordinatorSource: value.coordinatorSource });
    }).catch(e => { if (!controller.signal.aborted) setError((e as Error).message); });
    return () => controller.abort();
  }, [runId, attempt]);
  return <section className="panel risk-desk">
    <p className="eyebrow">06 / UNDERWRITER DESK</p><h2>Underwrite the evidence, not the excitement.</h2>
    <p className="muted">Deterministic policy over 45 Rust scenario runs. This desk recommends inventory planning limits, not loans or fund transfers.</p>
    {error && <div role="alert" className="error-banner">{error} <button onClick={() => setAttempt(n => n + 1)}>Retry audit</button></div>}
    {!report && !error && <p aria-live="polite">Reading the actual scenario summaries…</p>}
    {report && <>
      <div className="risk-summary">
        <div><p className="eyebrow">POLICY VERDICT</p><strong className={`verdict verdict-${report.policyVerdict.toLowerCase()}`} data-testid="policy-verdict">{report.policyVerdict}</strong><p className="fine">Server policy, not model opinion</p></div>
        <div><p className="eyebrow">PROPOSED INVENTORY PREPARATION CAP</p><strong>{money(report.recommendedCapCents)}</strong><p className="fine">Booth fee and labor remain outside this cap</p></div>
      </div>
      {report.policyVerdict === 'NEEDS_INPUT' && <p className="notice">At least one cost was unconfirmed. Start a new intake, review the costs, and approve again to obtain a fully informed verdict.</p>}
      <div className="table-scroll"><table data-testid="scenario-table"><caption>Turnout stress tests · 15 seeds each · P10 is the second-lowest profit</caption><thead><tr><th scope="col">Turnout</th><th scope="col">Attendees</th><th scope="col">Break-even k/n</th><th scope="col">Median sales</th><th scope="col">Median profit</th><th scope="col">P10 profit</th><th scope="col">Queue / price</th></tr></thead><tbody>
        {(['LOW', 'BASE', 'HIGH'] as const).map(name => {
          const s = report.scenarios.find(row => row.scenarioName === name)!;
          return <tr key={name}><th scope="row">{name}</th><td>{s.turnoutCount}</td><td>{s.profitableRuns}/{s.seedsRun}</td><td>{money(s.medianRevenueCents)}</td><td>{money(s.medianProfitCents)}</td><td>{money(s.downsideP10ProfitCents)}</td><td>{s.medianBalkedQueue} / {s.medianBalkedPrice}</td></tr>;
        })}
      </tbody></table></div>
      <p className="fine">Break-even means net profit ≥ $0. Seed frequencies are not calibrated real-world probabilities.</p>
      <div className="risk-columns">
        <section><h3>Bottleneck diagnosis</h3><p>{report.bottleneckDiagnosis}</p><h3>Policy order</h3><ol className="policy-order">
          <li>Unknown costs → NEEDS_INPUT</li><li>BASE break-even below 50% or organizer cut above 25% → REJECT</li><li>LOW P10 loss beyond 30% of upfront capital → REFER</li><li>Otherwise → APPROVE (recommendation only)</li>
        </ol></section>
        <section><div className="panel-heading"><h3>Underwriting diff</h3><span className="badge">{sourceLabel(report.coordinatorSource)}</span></div><pre className="diff">{report.droidDiffText}</pre><p className="fine">Generated by deterministic policy. Factory Droid is not claimed for fallback runs.</p></section>
      </div>
      <details open><summary>Grounded risk narrative · {sourceLabel(report.narrativeSource)}</summary><p className="audit-narrative">{report.narrativeMarkdown}</p></details>
      <p className="fine hash">Run {report.runId}<br />Config {report.configHash} · {report.provenance}</p>
    </>}
  </section>;
}
